/**
 * The Mystery Book catalog: a small, hand-curated set of real titles with the structured metadata (Section 13.7
 * "Book Metadata") the recommendation engine needs — genre, a mood profile, themes, pace, length, popularity —
 * none of which a user's own free-text library `Book.genres` can provide. This is a deliberate stand-in for what
 * the spec calls out as a real operational prerequisite: a team/founder-maintained catalog with its own curation
 * tooling. That tooling does not exist yet (see README "Known limits"); until it does, this file *is* the
 * catalog. `slug` is stable and referenced by `MysteryPick.bookSlug` — never rename one, only add or retire.
 *
 * Book titles and author names are never translated (Section 15) — only ever shown in their original English.
 */
export interface CatalogBook {
  slug: string;
  title: string;
  author: string;
  language: "en";
  genre: MysteryGenreKey;
  subgenre: string;
  /** 0–1 per mood; a book need not score on every mood (omitted = 0). See Section 10 — never a flat genre map. */
  moodProfile: Partial<Record<MoodKey, number>>;
  themes: string[];
  pace: "slow" | "medium" | "fast";
  pages: number;
  /** 0–1, standing in for Section 13.7's "Rating/popularity" until real ratings data exists. */
  popularity: number;
  ageSuitability: "all" | "teen" | "adult";
  /** Section 11's "out of stock" filter needs a real flag to check — always true today (no inventory system
   *  exists yet), kept here so that filter is structurally real rather than silently absent. */
  available: boolean;
  coverUrl: string | null;
}

